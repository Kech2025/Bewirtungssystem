			--
-- Anpassungen an der bestehenden PostgreSQL-Datenbank vor der Code-Migration.
-- Diese Skripte setzen die Entscheidungen um:
--   1. bit(1) -> boolean für alle Status-/Flag-Spalten
--   2. wordvorlage.vorlage: bytea[] -> bytea (einzelnes BLOB)
--   3. gequotete Mixed-Case-Spalten -> lowercase
--
-- WICHTIG: Vorher ein Backup (pg_dump) ziehen. Reihenfolge beachten.
--

-- 1. bit(1) -> boolean
-- ('1' = true, sonst false). USING-Klausel konvertiert vorhandene Werte.
ALTER TABLE public.bewirtungsauftrag
	ALTER COLUMN status TYPE boolean USING (status = B'1'),
	ALTER COLUMN statuslieferung TYPE boolean USING (statuslieferung = B'1');

ALTER TABLE public.bewirtungsposition
	ALTER COLUMN status TYPE boolean USING (status = B'1');

ALTER TABLE public.globalepreisliste
	ALTER COLUMN druck TYPE boolean USING (druck = B'1'),
	ALTER COLUMN status TYPE boolean USING (status = B'1');

ALTER TABLE public.globalepreislistezusatz
	ALTER COLUMN druck TYPE boolean USING (druck = B'1'),
	ALTER COLUMN status TYPE boolean USING (status = B'1');

ALTER TABLE public.tisch
	ALTER COLUMN sofortlieferung TYPE boolean USING (sofortlieferung = B'1');

ALTER TABLE public.verein
	ALTER COLUMN status TYPE boolean USING (status = B'1');

ALTER TABLE public.wordvorlage
	ALTER COLUMN komplett TYPE boolean USING (komplett = B'1');

-- 2. wordvorlage.inhalt: bytea[] -> bytea
-- Der Dateiinhalt liegt in der Spalte "inhalt" (Array). Es wird das erste
-- Element übernommen; bei leerer Tabelle genügt der einfache Typwechsel.
ALTER TABLE public.wordvorlage
	ALTER COLUMN inhalt TYPE bytea USING (CASE WHEN inhalt IS NULL THEN NULL ELSE inhalt[1] END);

-- 3. Mixed-Case-Spalten -> lowercase
ALTER TABLE public.eventlog RENAME COLUMN "Source" TO source;
ALTER TABLE public.verein RENAME COLUMN "überschriftspeisekarte" TO ueberschriftspeisekarte;

-- 4. benutzer.administrator: integer -> boolean
ALTER TABLE public.benutzer
	ALTER COLUMN administrator TYPE boolean USING (administrator <> 0);

-- 5. Fehlende IDENTITY-Spalten (Primärschlüssel waren in SQLite auto-increment).
-- In PostgreSQL muss der automatische Wert explizit als IDENTITY definiert werden.
ALTER TABLE public.bereichtische
	ALTER COLUMN bereichid ADD GENERATED BY DEFAULT AS IDENTITY;
