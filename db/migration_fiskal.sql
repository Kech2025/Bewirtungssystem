--
-- Fiskal-/TSE-Tabellen gemäß KassenSichV / DSFinV-K.
-- Diese Tabellen bilden unveränderbare Geschäftsvorfälle (Belege) samt
-- TSE-Signaturen und Kassenabschlüssen (Z-Bons) ab.
--
-- WICHTIG: Vorher ein Backup (pg_dump) ziehen. Reihenfolge beachten
-- (Haupttabelle vor abhängigen Tabellen wegen Fremdschlüsseln).
--
-- Grundsatz: Daten dürfen nach dem Abschluss NICHT mehr verändert oder
-- gelöscht werden. Stornos/Korrekturen sind eigene signierte Belege mit
-- Verweis auf den Ursprungsbeleg (ursprungsbelegid).
--

-- 1. Fiskalisierter Beleg (Bon) - entspricht DSFinV-K transactions.csv
CREATE TABLE public.fiskal_beleg (
	id integer GENERATED BY DEFAULT AS IDENTITY,
	belegnummer bigint NOT NULL,
	kasseid text NOT NULL,
	bediener text,
	vorgangstyp integer NOT NULL DEFAULT 0,   -- 0=Beleg, 1=Storno, 2=Korrektur
	status integer NOT NULL DEFAULT 0,        -- 0=Offen, 1=Abgeschlossen, 2=Abgebrochen
	zahlart integer NOT NULL DEFAULT 0,       -- 0=Bar, 1=Unbar
	startzeitpunkt timestamp without time zone NOT NULL,
	endzeitpunkt timestamp without time zone,
	gesamtbrutto numeric(12,2) NOT NULL DEFAULT 0,
	ursprungsbelegid integer
);

-- 2. Positionszeilen eines Belegs - entspricht DSFinV-K lines.csv
CREATE TABLE public.fiskal_position (
	id integer GENERATED BY DEFAULT AS IDENTITY,
	belegid integer NOT NULL,
	positionsnummer integer NOT NULL,
	artikel text NOT NULL,
	menge numeric(12,3) NOT NULL DEFAULT 0,
	einzelpreisbrutto numeric(12,2) NOT NULL DEFAULT 0,
	gesamtbrutto numeric(12,2) NOT NULL DEFAULT 0,
	mwstsatz numeric(5,2) NOT NULL DEFAULT 0
);

-- 3. Steuerliche Aufteilung je Steuersatz - entspricht DSFinV-K businesscases.csv
CREATE TABLE public.fiskal_steuer (
	id integer GENERATED BY DEFAULT AS IDENTITY,
	belegid integer NOT NULL,
	steuerschluessel integer NOT NULL,        -- 1=19%, 2=7%, ...
	mwstsatz numeric(5,2) NOT NULL DEFAULT 0,
	brutto numeric(12,2) NOT NULL DEFAULT 0,
	netto numeric(12,2) NOT NULL DEFAULT 0,
	steuer numeric(12,2) NOT NULL DEFAULT 0
);

-- 4. TSE-Signaturdaten eines Vorgangs - entspricht DSFinV-K tse.csv
CREATE TABLE public.fiskal_signatur (
	id integer GENERATED BY DEFAULT AS IDENTITY,
	belegid integer NOT NULL,
	tseseriennummer text NOT NULL,
	transaktionsnummer bigint NOT NULL,
	signaturzaehler bigint NOT NULL,
	signatur text,
	signaturalgorithmus text,
	zertifikatreferenz text,
	tsestartzeit timestamp without time zone,
	tseendzeit timestamp without time zone,
	prozesstyp text,
	qrcodedaten text
);

-- 5. Kassenabschluss (Z-Bon) - entspricht DSFinV-K cashpointclosing.csv
CREATE TABLE public.fiskal_abschluss (
	id integer GENERATED BY DEFAULT AS IDENTITY,
	znummer bigint NOT NULL,
	kasseid text NOT NULL,
	erstzeitpunkt timestamp without time zone,
	letztzeitpunkt timestamp without time zone,
	abschlusszeitpunkt timestamp without time zone NOT NULL,
	vonbelegnummer bigint,
	bisbelegnummer bigint,
	summebrutto numeric(12,2) NOT NULL DEFAULT 0,
	summebar numeric(12,2) NOT NULL DEFAULT 0,
	summeunbar numeric(12,2) NOT NULL DEFAULT 0
);

--
-- Primärschlüssel
--
ALTER TABLE ONLY public.fiskal_beleg ADD CONSTRAINT fiskal_beleg_pkey PRIMARY KEY (id);
ALTER TABLE ONLY public.fiskal_position ADD CONSTRAINT fiskal_position_pkey PRIMARY KEY (id);
ALTER TABLE ONLY public.fiskal_steuer ADD CONSTRAINT fiskal_steuer_pkey PRIMARY KEY (id);
ALTER TABLE ONLY public.fiskal_signatur ADD CONSTRAINT fiskal_signatur_pkey PRIMARY KEY (id);
ALTER TABLE ONLY public.fiskal_abschluss ADD CONSTRAINT fiskal_abschluss_pkey PRIMARY KEY (id);

--
-- Fremdschlüssel
--
ALTER TABLE ONLY public.fiskal_position
	ADD CONSTRAINT fiskal_position_belegid_fkey FOREIGN KEY (belegid)
	REFERENCES public.fiskal_beleg (id);

ALTER TABLE ONLY public.fiskal_steuer
	ADD CONSTRAINT fiskal_steuer_belegid_fkey FOREIGN KEY (belegid)
	REFERENCES public.fiskal_beleg (id);

ALTER TABLE ONLY public.fiskal_signatur
	ADD CONSTRAINT fiskal_signatur_belegid_fkey FOREIGN KEY (belegid)
	REFERENCES public.fiskal_beleg (id);

ALTER TABLE ONLY public.fiskal_beleg
	ADD CONSTRAINT fiskal_beleg_ursprungsbelegid_fkey FOREIGN KEY (ursprungsbelegid)
	REFERENCES public.fiskal_beleg (id);

--
-- Eindeutigkeit / Indizes
--
-- Lückenlose, eindeutige Belegnummer je Kasse.
ALTER TABLE ONLY public.fiskal_beleg
	ADD CONSTRAINT fiskal_beleg_kasse_belegnummer_key UNIQUE (kasseid, belegnummer);

-- Eindeutige Z-Nummer je Kasse.
ALTER TABLE ONLY public.fiskal_abschluss
	ADD CONSTRAINT fiskal_abschluss_kasse_znummer_key UNIQUE (kasseid, znummer);

-- Eine Signatur je Beleg.
ALTER TABLE ONLY public.fiskal_signatur
	ADD CONSTRAINT fiskal_signatur_belegid_key UNIQUE (belegid);

CREATE INDEX fiskal_position_belegid_idx ON public.fiskal_position (belegid);
CREATE INDEX fiskal_steuer_belegid_idx ON public.fiskal_steuer (belegid);
CREATE INDEX fiskal_beleg_startzeitpunkt_idx ON public.fiskal_beleg (startzeitpunkt);
