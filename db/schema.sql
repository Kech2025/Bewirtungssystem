--
-- PostgreSQL-Schema für das Bewirtungssystem
-- Gemeinsame Datenbank für Bewirtung (Desktop), Bewirtung.Webserver und Bewirtung.Api.
-- Referenz für die Migration von SQLite auf PostgreSQL.
--
-- Namenskonvention: alles lowercase, zusammengeschrieben (BewirtungsDatum -> bewirtungsdatum).
-- Typen: Datum -> date, Geld -> numeric(10,2), Boolean -> boolean.
--

CREATE TABLE public.benutzer (
	userid integer NOT NULL
	-- weitere Spalten: siehe Datenbank (CREATE-Teil im Dump oberhalb von OWNER)
);

ALTER TABLE public.benutzer ALTER COLUMN userid ADD GENERATED BY DEFAULT AS IDENTITY (
	SEQUENCE NAME public.benutzer_userid_seq
	START WITH 1 INCREMENT BY 1 NO MINVALUE NO MAXVALUE CACHE 1
);

CREATE TABLE public.bereichtische (
	bereichid integer NOT NULL,
	bezeichnung text
);

ALTER TABLE public.bereichtische ALTER COLUMN bereichid ADD GENERATED BY DEFAULT AS IDENTITY (
	SEQUENCE NAME public.bereichtische_bereichid_seq
	START WITH 1 INCREMENT BY 1 NO MINVALUE NO MAXVALUE CACHE 1
);

CREATE TABLE public.bewirtungsauftrag (
	auftragid integer NOT NULL,
	userid integer,
	gesamtpreis numeric(10,2),
	bezahlt numeric(10,2),
	tischnummer integer,
	pagerno integer,
	pagermethode integer,
	bewirtungstermin date,
	startdatetime timestamp without time zone,
	enddatetime timestamp without time zone,
	status boolean,
	statuslieferung boolean
);

ALTER TABLE public.bewirtungsauftrag ALTER COLUMN auftragid ADD GENERATED BY DEFAULT AS IDENTITY (
	SEQUENCE NAME public.bewirtungsauftrag_auftragid_seq
	START WITH 1 INCREMENT BY 1 NO MINVALUE NO MAXVALUE CACHE 1
);

CREATE TABLE public.bewirtungsposition (
	bewirtungsauftragid integer NOT NULL,
	bewirtungsposition integer NOT NULL,
	preislisteid integer,
	preislistezusatzid integer,
	preis numeric(10,2),
	pager integer,
	menge integer,
	mengebezahlt integer,
	besonderheit text,
	mengegeliefert integer,
	buchungszeitpunkt text,
	status boolean
);

CREATE TABLE public.eventlog (
	id integer NOT NULL,
	source text NOT NULL,
	message text NOT NULL,
	stacktrace text,
	createdate timestamp without time zone
);

ALTER TABLE public.eventlog ALTER COLUMN id ADD GENERATED BY DEFAULT AS IDENTITY (
	SEQUENCE NAME public.eventlog_id_seq
	START WITH 1 INCREMENT BY 1 NO MINVALUE NO MAXVALUE CACHE 1
);

CREATE TABLE public.globalepreisliste (
	id integer NOT NULL,
	name text,
	preiskategorie integer,
	bildpfad text,
	zusatztext text,
	druck boolean,
	status boolean
);

ALTER TABLE public.globalepreisliste ALTER COLUMN id ADD GENERATED BY DEFAULT AS IDENTITY (
	SEQUENCE NAME public.globalepreisliste_id_seq
	START WITH 1 INCREMENT BY 1 NO MINVALUE NO MAXVALUE CACHE 1
);

CREATE TABLE public.globalepreislistezusatz (
	id integer NOT NULL,
	speisekarteid integer,
	bezeichnung text,
	bildpfad text,
	druck boolean,
	status boolean
);

ALTER TABLE public.globalepreislistezusatz ALTER COLUMN id ADD GENERATED BY DEFAULT AS IDENTITY (
	SEQUENCE NAME public.globalepreislistezusatz_id_seq
	START WITH 1 INCREMENT BY 1 NO MINVALUE NO MAXVALUE CACHE 1
);

CREATE TABLE public.globalerpreis (
	globalepreislisteid integer NOT NULL,
	zusatzid integer NOT NULL,
	preis numeric(10,2),
	gueltigbis date,
	gueltigab date NOT NULL
);

CREATE TABLE public.helfertermin (
	vereinid integer NOT NULL,
	userid integer NOT NULL,
	bewirtungsdatum date NOT NULL
);

CREATE TABLE public.mwst (
	preiskategorie integer NOT NULL,
	mwst numeric(10,2)
);

CREATE TABLE public.pagerstatus (
	pagerno integer NOT NULL,
	positionid integer NOT NULL,
	status integer,
	startdatetime timestamp without time zone,
	enddatetime timestamp without time zone
);

CREATE TABLE public.preislistetermin (
	preislisteid integer NOT NULL,
	preislistezusatzid integer NOT NULL,
	vereinid integer NOT NULL,
	preis numeric(10,2),
	bewirtungsdatum date NOT NULL
);

CREATE TABLE public.termin (
	vereinid integer NOT NULL,
	bewirtungsdatum date NOT NULL
);

CREATE TABLE public.tisch (
	tischnummer integer NOT NULL,
	bereichid integer,
	sofortlieferung boolean
);

CREATE TABLE public.tischtermin (
	vereinid integer NOT NULL,
	tischnummer integer NOT NULL,
	bewirtungsdatum date NOT NULL
);

CREATE TABLE public.verein (
	id integer NOT NULL,
	name text,
	ansprechpartnerid integer,
	strasse text,
	plz text,
	ort text,
	ueberschriftspeisekarte text,
	status boolean
);

ALTER TABLE public.verein ALTER COLUMN id ADD GENERATED BY DEFAULT AS IDENTITY (
	SEQUENCE NAME public.verein_id_seq
	START WITH 1 INCREMENT BY 1 NO MINVALUE NO MAXVALUE CACHE 1
);

CREATE TABLE public.wordvorlage (
	id integer CONSTRAINT wordvorlagen_id_not_null NOT NULL,
	inhalt bytea,
	dateiname text,
	komplett boolean,
	bewirtungsdatum date
);

ALTER TABLE public.wordvorlage ALTER COLUMN id ADD GENERATED BY DEFAULT AS IDENTITY (
	SEQUENCE NAME public.wordvorlagen_id_seq
	START WITH 1 INCREMENT BY 1 NO MINVALUE NO MAXVALUE CACHE 1
);

--
-- Primärschlüssel
--
ALTER TABLE ONLY public.benutzer ADD CONSTRAINT benutzer_pkey PRIMARY KEY (userid);
ALTER TABLE ONLY public.bereichtische ADD CONSTRAINT bereichtische_pkey PRIMARY KEY (bereichid);
ALTER TABLE ONLY public.bewirtungsauftrag ADD CONSTRAINT bewirtungsauftrag_pkey PRIMARY KEY (auftragid);
ALTER TABLE ONLY public.bewirtungsposition ADD CONSTRAINT bewirtungsposition_pkey PRIMARY KEY (bewirtungsauftragid, bewirtungsposition);
ALTER TABLE ONLY public.eventlog ADD CONSTRAINT eventlog_pkey PRIMARY KEY (id);
ALTER TABLE ONLY public.globalepreisliste ADD CONSTRAINT globalepreisliste_pkey PRIMARY KEY (id);
ALTER TABLE ONLY public.globalepreislistezusatz ADD CONSTRAINT globalepreislistezusatz_pkey PRIMARY KEY (id);
ALTER TABLE ONLY public.globalerpreis ADD CONSTRAINT globalerpreis_pkey PRIMARY KEY (gueltigab, globalepreislisteid, zusatzid);
ALTER TABLE ONLY public.helfertermin ADD CONSTRAINT helfertermin_pkey PRIMARY KEY (bewirtungsdatum, userid, vereinid);
ALTER TABLE ONLY public.mwst ADD CONSTRAINT mwst_pkey PRIMARY KEY (preiskategorie);
ALTER TABLE ONLY public.pagerstatus ADD CONSTRAINT pagerstatus_pkey PRIMARY KEY (pagerno, positionid);
ALTER TABLE ONLY public.preislistetermin ADD CONSTRAINT preislistetermin_pkey PRIMARY KEY (bewirtungsdatum, vereinid, preislistezusatzid, preislisteid);
ALTER TABLE ONLY public.termin ADD CONSTRAINT termin_pkey PRIMARY KEY (bewirtungsdatum, vereinid);
ALTER TABLE ONLY public.tisch ADD CONSTRAINT tisch_pkey PRIMARY KEY (tischnummer);
ALTER TABLE ONLY public.tischtermin ADD CONSTRAINT tischtermin_pkey PRIMARY KEY (bewirtungsdatum, tischnummer, vereinid);
ALTER TABLE ONLY public.verein ADD CONSTRAINT verein_pkey PRIMARY KEY (id);
ALTER TABLE ONLY public.wordvorlage ADD CONSTRAINT wordvorlagen_pkey PRIMARY KEY (id);
